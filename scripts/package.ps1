[CmdletBinding()]
param([string]$CrtDirectory)

$ErrorActionPreference = 'Stop'
if ($env:GITHUB_ACTIONS -ne 'true' -or !$env:GITHUB_RUN_ID) {
    throw 'Distribution packages must be generated by GitHub Actions. Use build.cmd for local development.'
}
$root = Split-Path $PSScriptRoot -Parent
Set-Location $root
$version = [regex]::Match((Get-Content CMakeLists.txt -Raw), 'VERSION (\d+\.\d+\.\d+)').Groups[1].Value
if (!$version) { throw 'CMake project version missing' }
if ($env:GITHUB_REF -like 'refs/tags/*' -and $env:GITHUB_REF_NAME -ne "v$version") {
    throw "Release tag must match CMakeLists.txt: v$version"
}

function Get-Sha256([string]$Path) {
    $stream = [IO.File]::OpenRead($Path)
    $sha = [Security.Cryptography.SHA256]::Create()
    try { [BitConverter]::ToString($sha.ComputeHash($stream)).Replace('-', '').ToLowerInvariant() }
    finally { $stream.Dispose(); $sha.Dispose() }
}

$loaderHashes = @{
    'shroudtopia.dll' = '53ceee2dd51c12b7db1371092eddcd1118abeaeaba6e3b482986a071ab9b1a11'
    'winmm.dll' = '2519ab074597c39f9241456711370cac907e86957833a7ae16705714ce6d7297'
}
foreach ($name in $loaderHashes.Keys) {
    if ((Get-Sha256 "$root/dependencies/shroudtopia/$name") -ne $loaderHashes[$name]) {
        throw "Bundled Shroudtopia hash mismatch: $name"
    }
}
$dll = Join-Path $root 'build/livemap.dll'
if (![Text.Encoding]::ASCII.GetString([IO.File]::ReadAllBytes($dll)).Contains('CreateModInstance')) {
    throw 'Livemap DLL does not export the Shroudtopia adapter factory'
}
if (!$CrtDirectory) {
    $vswhere = "${env:ProgramFiles(x86)}/Microsoft Visual Studio/Installer/vswhere.exe"
    $vs = & $vswhere -latest -products '*' -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath
    if (!$vs) { throw 'Visual Studio C++ installation not found' }
    $CrtDirectory = Get-ChildItem "$vs/VC/Redist/MSVC/*/x64/Microsoft.VC*.CRT" -Directory |
        Sort-Object FullName -Descending | Select-Object -First 1 -ExpandProperty FullName
}
foreach ($name in @('msvcp140.dll', 'vcruntime140.dll', 'vcruntime140_1.dll')) {
    if (!(Test-Path -LiteralPath (Join-Path $CrtDirectory $name))) { throw "Missing x64 CRT: $name" }
}
$crtFiles = @(Get-ChildItem -LiteralPath $CrtDirectory -Filter '*.dll' -File)
$web = Join-Path $root 'web'
$assets = @('index.html', 'maps.json', 'pois.json', 'pois.json.gz', 'loot.json', 'loot.json.gz',
    'weather.json', 'weather.json.gz', 'shroud.png')
foreach ($folder in @('icons', 'tiles', 'tiles-hd', 'ui', 'fonts')) {
    $assets += @(Get-ChildItem -LiteralPath "$web/$folder" -Recurse -File | ForEach-Object {
        $_.FullName.Substring($web.Length + 1).Replace('\', '/')
    })
}
$output = Join-Path $root 'dist/distribution'
New-Item -ItemType Directory -Force -Path $output | Out-Null
$deliverables = @('livemap.dll', 'iphlpapi.dll', 'EnshroudedWithLivemap.exe')
foreach ($name in $deliverables) { Copy-Item -LiteralPath "$root/build/$name" -Destination $output -Force }

Add-Type -AssemblyName System.IO.Compression.FileSystem
foreach ($package in @('standard', 'full')) {
    $stage = Join-Path $root ("dist/package-stage-" + [guid]::NewGuid().ToString('N'))
    New-Item -ItemType Directory -Force -Path "$stage/mods", "$stage/licenses", "$stage/livemap" | Out-Null
    try {
        Copy-Item -LiteralPath $dll -Destination "$stage/mods/livemap.dll"
        foreach ($name in $loaderHashes.Keys) { Copy-Item -LiteralPath "$root/dependencies/shroudtopia/$name" -Destination $stage }
        Copy-Item -LiteralPath "$root/package/shroudtopia.example.json" -Destination "$stage/shroudtopia.json"
        Copy-Item -LiteralPath "$root/package/livemap.example.ini" -Destination "$stage/livemap.ini"
        Copy-Item -LiteralPath "$root/package/README.txt", "$root/package/README-HD.txt" -Destination $stage
        Copy-Item -LiteralPath "$root/LICENSE" -Destination "$stage/licenses/Livemap-LICENSE.txt"
        Copy-Item -LiteralPath "$root/THIRD_PARTY_NOTICES.md" -Destination "$stage/licenses/THIRD_PARTY_NOTICES.md"
        Copy-Item -LiteralPath "$root/dependencies/shroudtopia/LICENSE.txt" -Destination "$stage/licenses/Shroudtopia-LICENSE.txt"
        Copy-Item -LiteralPath "$root/dependencies/shroudtopia/README.md" -Destination "$stage/licenses/shroudtopia-README.md"
        $allowed = @('mods/livemap.dll', 'shroudtopia.dll', 'winmm.dll', 'shroudtopia.json', 'livemap.ini',
            'README.txt', 'README-HD.txt', 'licenses/Livemap-LICENSE.txt', 'licenses/THIRD_PARTY_NOTICES.md',
            'licenses/Shroudtopia-LICENSE.txt', 'licenses/shroudtopia-README.md')
        foreach ($asset in $assets) {
            $destination = Join-Path "$stage/livemap" $asset
            New-Item -ItemType Directory -Force -Path (Split-Path $destination -Parent) | Out-Null
            Copy-Item -LiteralPath (Join-Path $web $asset) -Destination $destination
            $allowed += "livemap/$asset"
        }
        if ($package -eq 'full') {
            foreach ($file in $crtFiles) {
                Copy-Item -LiteralPath $file.FullName -Destination $stage
                $allowed += $file.Name
            }
            Copy-Item -LiteralPath "$root/package/Microsoft-runtime-NOTICE.txt" -Destination "$stage/licenses/Microsoft-runtime-NOTICE.txt"
            $allowed += 'licenses/Microsoft-runtime-NOTICE.txt'
        }
        $staged = @(Get-ChildItem -LiteralPath $stage -Recurse -File)
        if ($staged.Count -ne $allowed.Count) { throw 'Unexpected package file count' }
        $files = @($staged | Sort-Object FullName | ForEach-Object {
            $relative = $_.FullName.Substring($stage.Length + 1).Replace('\', '/')
            if ($relative -cnotin $allowed) { throw "Unexpected package file: $relative" }
            [ordered]@{ path = $relative; sha256 = Get-Sha256 $_.FullName; bytes = $_.Length }
        })
        [ordered]@{ version = $version; variant = 'shroudtopia'; package = $package; commit = $env:GITHUB_SHA; files = $files } |
            ConvertTo-Json -Depth 6 | Set-Content "$stage/package-manifest.json" -Encoding utf8
        $zipName = if ($package -eq 'full') { "livemap-$version-full.zip" } else { "livemap-$version.zip" }
        $zip = Join-Path $output $zipName
        Compress-Archive -Path "$stage/*" -DestinationPath $zip -Force
        $archive = [IO.Compression.ZipFile]::OpenRead($zip)
        try {
            $entries = @($archive.Entries | Where-Object { !$_.FullName.EndsWith('/') })
            if ($entries.Count -ne ($allowed.Count + 1)) { throw 'Unexpected ZIP entry count' }
            $entryByPath = @{}
            foreach ($entry in $entries) {
                $relative = $entry.FullName.Replace('\', '/')
                if ($relative -cnotin ($allowed + 'package-manifest.json') -or $entryByPath.ContainsKey($relative)) {
                    throw "Unexpected ZIP entry: $($entry.FullName)"
                }
                $entryByPath[$relative] = $entry
            }
            foreach ($file in $files) {
                $entry = $entryByPath[$file.path]
                if (!$entry -or $entry.Length -ne $file.bytes) { throw "ZIP entry missing or incomplete: $($file.path)" }
                $stream = $entry.Open()
                $sha = [Security.Cryptography.SHA256]::Create()
                try { $hash = [BitConverter]::ToString($sha.ComputeHash($stream)).Replace('-', '').ToLowerInvariant() }
                finally { $stream.Dispose(); $sha.Dispose() }
                if ($hash -ne $file.sha256) { throw "ZIP hash mismatch: $($file.path)" }
            }
        } finally { $archive.Dispose() }
        $deliverables += $zipName
        Write-Host "Verified $package package: $zip"
    } finally {
        $resolved = [IO.Path]::GetFullPath($stage)
        if ((Split-Path $resolved -Parent) -ne [IO.Path]::GetFullPath((Join-Path $root 'dist')) -or
            (Split-Path $resolved -Leaf) -notmatch '^package-stage-[a-f0-9]{32}$') { throw 'Unexpected stage cleanup path' }
        Remove-Item -LiteralPath $resolved -Recurse -Force
    }
}
$deliverables | ForEach-Object { "$(Get-Sha256 (Join-Path $output $_))  $_" } |
    Set-Content "$output/SHA256SUMS.txt" -Encoding ascii
Write-Host "Verified distribution files: $output"
